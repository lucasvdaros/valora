namespace Valora.Domain;

public enum EntryKind
{
    Income,
    Expense
}

public enum EntryStatus
{
    Complete,
    PendingAmount
}

public sealed class Entry
{
    private Entry() { }

    public Entry(Guid id, MonthKey month, EntryKind kind, string description, MoneyAmount? amount,
        EntryStatus status, Guid? recurrenceRuleId, Guid? recurrenceRuleVersionId, string? note)
    {
        if (string.IsNullOrWhiteSpace(description))
            throw new ArgumentException("Description is required.", nameof(description));
        if ((status == EntryStatus.PendingAmount) != !amount.HasValue)
            throw new ArgumentException("Only pending entries may omit the amount.");
        if ((recurrenceRuleId is null) != (recurrenceRuleVersionId is null))
            throw new ArgumentException("Recurring entries must reference both a rule and its version.");

        Id = id;
        Month = month;
        Kind = kind;
        Description = description.Trim();
        Amount = amount;
        Status = status;
        RecurrenceRuleId = recurrenceRuleId;
        RecurrenceRuleVersionId = recurrenceRuleVersionId;
        Note = note?.Trim();
    }

    public Guid Id { get; private set; }
    public MonthKey Month { get; private set; }
    public EntryKind Kind { get; private set; }
    public string Description { get; private set; } = "";
    public MoneyAmount? Amount { get; private set; }
    public EntryStatus Status { get; private set; }
    public Guid? RecurrenceRuleId { get; private set; }
    public Guid? RecurrenceRuleVersionId { get; private set; }
    public string? Note { get; private set; }

    public bool IsRecurring => RecurrenceRuleId is not null;

    public void Update(MoneyAmount? amount, string description, string? note)
    {
        if (IsRecurring && amount is null)
            throw new ArgumentException("Recurring entries may be pending only when generated by a leave_pending rule.");
        if (string.IsNullOrWhiteSpace(description))
            throw new ArgumentException("Description is required.", nameof(description));

        Amount = amount;
        Status = amount.HasValue ? EntryStatus.Complete : EntryStatus.PendingAmount;
        Description = description.Trim();
        Note = note?.Trim();
    }

    public void ApplyRuleVersion(RecurrenceRuleVersion version)
    {
        if (RecurrenceRuleId != version.RuleId)
            throw new InvalidOperationException("The recurrence version does not belong to this entry.");

        RecurrenceRuleVersionId = version.Id;
        Kind = version.Kind;
        Description = version.Description;
        Amount = version.ValueMode == RecurrenceValueMode.CopyDefault ? version.DefaultAmount : null;
        Status = Amount.HasValue ? EntryStatus.Complete : EntryStatus.PendingAmount;
    }
}
